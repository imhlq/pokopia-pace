static int builder_boost_item_allowed(uint32_t item_id) {
    uint32_t lo = 0, hi = (uint32_t)BUILDER_BOOST_ELIGIBLE_ITEM_COUNT;
    while (lo < hi) {
        uint32_t mid = lo + (hi - lo) / 2;
        uint32_t value = kBuilderBoostEligibleItems[mid];
        if (value < item_id) lo = mid + 1;
        else if (value > item_id) hi = mid;
        else return 1;
    }
    return 0;
}
